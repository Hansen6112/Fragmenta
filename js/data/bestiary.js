function creaturesForTags(tagList, nation) {
  return Object.entries(BESTIARY)
    .filter(([id, c]) => {
      if (c.nations && !c.nations.includes(nation)) return false;
      return c.tags.some((t) => tagList.includes(t));
    })
    .map(([id]) => id);
}
