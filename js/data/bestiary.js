// Creature `tags` were authored against data/creaturetags.js's
// HABITAT_TAGS vocabulary ("mountains", "ruins", "underground", ...), but
// every spawn source emits world.js's TERRAIN_TAGS vocabulary ("mountain",
// "ruin", "cave", ...) and creaturesForTags matches exact strings. Result:
// 17 creatures (every ruin/underground construct and undead, Bone Roc,
// Mountain Lion, the Keth-Rhovael Guardian/Queen, ...) could never spawn
// anywhere, and ~50 more only spawned through their other tags. Normalized
// once here, at load, so everything downstream sees one vocabulary.
// `hills` has no terrain of its own — mapped to mountain (every hills
// creature also carries a forest/plains tag). Tyler: adjust if that's not
// the intended habitat.
const HABITAT_TO_TERRAIN_TAG = {
  mountains: ["mountain"],
  hills: ["mountain"],
  ruins: ["ruin"],
  underground: ["cave"],
  arctic: ["tundra"],
  ocean: ["sea"],
  wetlands: ["swamp"],
};
for (const creature of Object.values(BESTIARY)) {
  if (!Array.isArray(creature.tags)) continue;
  creature.tags = [...new Set(creature.tags.flatMap((t) => HABITAT_TO_TERRAIN_TAG[t] || [t]))];
}

function creaturesForTags(tagList, nation) {
  return Object.entries(BESTIARY)
    .filter(([id, c]) => {
      // Defensive guard (Phase 0): a special:true creature (Dregnar
      // Ashvein, scripted-encounter-only) must never leak into an ordinary
      // hunt/wild-spawn pool through a shared tag, even one it carries for
      // flavor/lore grouping rather than spawn eligibility.
      if (c.special) return false;
      if (c.nations && !c.nations.includes(nation)) return false;
      return c.tags.some((t) => tagList.includes(t));
    })
    .map(([id]) => id);
}

// Re-filters an already habitat/nation-matched creature id pool (from
// creaturesForTags) down to the ones whose Spawn Rarity band actually
// covers `level` (see data/creaturetags.js isLevelEligibleForRarity) —
// this is what makes the encounter pool skew toward rarer creatures as
// the player levels up. A PREFERENCE, not a hard requirement: if nothing
// in the pool is in-band at this level (e.g. no Epic-rarity creature
// exists yet, so levels 16-19 have a gap), falls back to the full
// unfiltered pool rather than silently producing zero encounters —
// whatever gets picked still gets its level clamped to its own band in
// startCombat, so it stays balanced either way.
function creaturesEligibleAtLevel(pool, level) {
  const eligible = pool.filter((id) => isLevelEligibleForRarity(level, BESTIARY[id].spawnRarity));
  return eligible.length ? eligible : pool;
}
